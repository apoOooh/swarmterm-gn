test('custom mixed workspace recipe uses automatic accounts and persists without terminal text',async({page})=>{
  await page.goto('/tests/fixtures/app.html?welcome=1')
  await expect(page.getByRole('heading',{name:'Compose',exact:true})).toBeVisible()
  await page.evaluate(()=>{(window as any).fixture.accounts.push({id:'claude-profile',agentId:'claude-code',name:'Claude team',configDir:'/accounts/claude'},{id:'codex-profile',agentId:'codex',name:'Codex team',configDir:'/accounts/codex'})})
  await settings(page)
  await page.getByRole('textbox',{name:'Custom action name',exact:true}).fill('Mixed squad')
  await page.getByRole('textbox',{name:'Workspace recipe agents',exact:true}).fill('claude-code,claude-code,codex,codex')
  await page.getByRole('textbox',{name:'Workspace recipe folder',exact:true}).fill('/project')
  await page.getByRole('button',{name:'Add workspace step',exact:true}).click();await page.getByRole('button',{name:'Save custom action',exact:true}).click()
  await page.getByRole('button',{name:'Run',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>(window as any).fixture.counters.created)).toBe(4)
  const spawns=await page.evaluate(()=>(window as any).fixture.counters.spawns)
  expect(spawns.map((s:any)=>s.agentId)).toEqual(['claude-code','claude-code','codex','codex'])
  expect(spawns.map((s:any)=>s.accountId)).toEqual([undefined,'claude-profile',undefined,'codex-profile'])
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('swarmterm-shortcuts-v1')!))
  expect(saved.macros[0].steps).toEqual([{type:'workspace',agentIds:['claude-code','claude-code','codex','codex'],cwd:'/project',accounts:'round-robin'}])
  await page.reload();await settings(page);await expect(page.getByText('Mixed squad',{exact:false}).first()).toBeVisible()
})
