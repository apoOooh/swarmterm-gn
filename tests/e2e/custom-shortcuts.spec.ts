import { test,expect,type Page } from '@playwright/test'
async function settings(page:Page){await page.getByRole('button',{name:'Settings',exact:true}).click();await page.getByRole('button',{name:'Keyboard Shortcuts',exact:true}).click()}
test('rebound shortcut is claimed once and its old chord reaches the terminal',async({page})=>{
  await page.goto('/tests/fixtures/app.html')
  await expect.poll(()=>page.evaluate(()=>(window as any).fixture?.counters.created ?? 0)).toBe(2)
  await settings(page)
  await page.getByRole('button',{name:'Record shortcut for Toggle sidebar',exact:true}).click()
  await page.keyboard.press('Control+Shift+K')
  await expect(page.getByRole('button',{name:'Record shortcut for Toggle sidebar',exact:true})).toHaveText('Mod+Shift+K')
  await page.getByRole('button',{name:'Close settings',exact:true}).click()
  await page.evaluate(async()=>{const {focusTerminal}=await import('/src/lib/terminal-registry.ts');const {selectFocusedTerminalId}=await import('/src/store/app-store.ts');focusTerminal(selectFocusedTerminalId((window as any).fixture.useAppStore.getState())!);(window as any).fixture.counters.writes.length=0})
  await page.keyboard.press('Control+Shift+K')
  expect(await page.evaluate(()=>(window as any).fixture.counters.writes)).toEqual([])
  await page.keyboard.down('Control');await page.keyboard.down('Shift');await page.keyboard.down('K')
  const heldVisibility=await page.evaluate(async()=>(await import('/src/store/navbar-visibility-store.ts')).useNavbarVisibilityStore.getState().visible)
  await page.keyboard.down('K');await page.keyboard.down('K')
  expect(await page.evaluate(async()=>(await import('/src/store/navbar-visibility-store.ts')).useNavbarVisibilityStore.getState().visible)).toBe(heldVisibility)
  expect(await page.evaluate(()=>(window as any).fixture.counters.writes)).toEqual([])
  await page.keyboard.up('K');await page.keyboard.up('Shift');await page.keyboard.up('Control')
  const visibility=await page.evaluate(async()=>(await import('/src/store/navbar-visibility-store.ts')).useNavbarVisibilityStore.getState().visible)
  await page.keyboard.press('Control+b')
  await expect.poll(()=>page.evaluate(()=>(window as any).fixture.counters.writes)).toEqual(['\x02'])
  expect(await page.evaluate(async()=>(await import('/src/store/navbar-visibility-store.ts')).useNavbarVisibilityStore.getState().visible)).toBe(visibility)
  await page.evaluate(async()=>{
    const {useShortcutStore}=await import('/src/store/shortcut-store.ts')
    const {useAgentStateStore}=await import('/src/store/agent-state-store.ts')
    useAgentStateStore.setState({byId:{}})
    if(!useShortcutStore.getState().bind('jump-to-attention','Mod+J'))throw new Error('Binding failed')
    ;(window as any).fixture.counters.writes.length=0
  })
  await page.keyboard.press('Control+j')
  expect(await page.evaluate(()=>(window as any).fixture.counters.writes)).toEqual([])
})
test('file shortcuts leave hidden documents unchanged while composer owns the keyboard',async({page})=>{
  await page.goto('/tests/fixtures/app.html')
  await expect(page.getByRole('treeitem',{name:'README.md',exact:true})).toBeVisible()
  await page.getByRole('treeitem',{name:'README.md',exact:true}).click()
  await page.getByRole('button',{name:'Markdown editor',exact:true}).click()
  await page.locator('.cm-content').first().click();await page.keyboard.press('Control+End');await page.keyboard.type(' pending changes')
  const read=()=>page.evaluate(()=>Object.values((window as any).fixture.useDocumentStore.getState().documents).find((d:any)=>d.path==='/project/README.md') as any)
  await expect.poll(async()=>(await read()).dirty).toBe(true)
  const before=await read()
  await page.evaluate(()=>(window as any).fixture.useAppStore.getState().openWelcome())
  await page.getByPlaceholder('Choose a folder…').focus()
  await page.keyboard.press('Control+s');await page.keyboard.press('Control+Shift+V')
  expect((await read()).dirty).toBe(true);expect((await read()).mode).toBe(before.mode)
  expect(await page.evaluate(()=>(window as any).fixture.files['/project/README.md'].content)).not.toContain('pending changes')
})
